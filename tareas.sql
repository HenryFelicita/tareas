-- Database: tareas
-- S11-1 Demo 1: tabla tarea de la base de datos tareas

create table tarea (
    -- Clave primaria que genera PostgreSQL (1, 2, 3...). El INSERT no la indica.
    id bigint generated by default as identity primary key,
    -- Obligatoria, de hasta 100 caracteres.
    titulo varchar(100) not null,
    -- Opcional: admite null.
    descripcion varchar(255),
    -- Una tarea nueva empieza sin completar si el INSERT no dice otra cosa.
    completada boolean not null default false
);

-- Tareas de ejemplo.
insert into tarea (titulo, descripcion, completada) values
    ('Preparar la demo de Git', 'Crear el repositorio local del proyecto', true),
    ('Practicar las ramas', 'Crear una rama, cambiarla y fusionarla', false),
    ('Cerrar la sesión', 'Subir el proyecto a un repositorio remoto', false);

-- Comprobación: debe devolver todas las filas.
select * from tarea;